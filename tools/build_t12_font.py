def glyph_map():
    out = {' ': [0]*5}
    out.update({chr(ord('0')+i): g for i,g in enumerate(digits)})
    out.update({chr(ord('A')+i): g for i,g in enumerate(letters)})
    out.update({chr(ord('a')+i): g for i,g in enumerate(lowercase)})
    out.update(symbols)
    return out

def make_glyph(columns, bold):
    pen = TTGlyphPen(None)
    pixels = {(x,y) for x,col in enumerate(columns) for y in range(7) if col & (1 << y)}
    if bold:
        pixels |= {(x+1,y) for x,y in pixels}
    for x,y in pixels:
        # Ten font units are one logical OLED pixel.  The em square is 70
        # units high, so sizes 7, 14, 21... map to exact integer pixel grids.
        x0, y0 = x * 10, (6-y) * 10
        pen.moveTo((x0,y0)); pen.lineTo((x0+10,y0)); pen.lineTo((x0+10,y0+10)); pen.lineTo((x0,y0+10)); pen.closePath()
    return pen.glyph()

def build(path, bold):
    glyphs = {'.notdef': make_glyph([], False)}
    metrics = {'.notdef': (60, 0)}
    cmap = {}
    for ch, columns in glyph_map().items():
        name = 'g%04X' % ord(ch)
        glyphs[name] = make_glyph(columns, bold)
        cmap[ord(ch)] = name
        metrics[name] = (70 if bold else 60, 0)
    glyph_order = ['.notdef'] + [n for n in glyphs if n != '.notdef']
    fb = FontBuilder(70, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=70, descent=0)
    fb.setupOS2(sTypoAscender=70, sTypoDescender=0, usWinAscent=70, usWinDescent=0)
    fb.setupPost()
    fb.setupNameTable({
        'familyName': 'T12 Pixel 5x7',
        'styleName': 'Bold' if bold else 'Regular',
        'fullName': 'T12 Pixel 5x7 Bold' if bold else 'T12 Pixel 5x7',
        'psName': 'T12Pixel5x7-Bold' if bold else 'T12Pixel5x7',
    })
    fb.setupHead(unitsPerEm=70)
    fb.save(path)

